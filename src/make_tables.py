# Published values, cited verbatim from their source papers (see docstring / task brief).
_PUBLISHED = [
    ("AuSR1 (Aminuddin \\& Ernawan 2022)", "45.57", r"$\approx$0.99", "27.64",
     "worst case reported; 2$\\times$2 blocks"),
    ("Wu et al.\\ (CMC 2025)", "$>$41", "--", "$>$30 @ 50\\% tamper",
     "0\\% FPR/FNR, 100\\% detection rate"),
    ("Korus \\& Dziech (IEEE TIP 2013)", "--", "--", "37 @ 50\\% damage",
     "fountain codes, $>$10{,}000 images"),
]


def build_baseline_comparison(rows: list[dict]) -> str:
    """Our measured numbers beside published literature values."""
    # Variant A only. Averaging A and B into one figure would report a number
    # (43.69 dB) that NEITHER variant produces -- A measures 43.18 and B 44.20,
    # and they differ for a structural reason (their payload value distributions
    # differ, see the paper's imperceptibility discussion). Variant A is the
    # primary configuration, so the comparison row reports A and says so.
    main_rows = [r for r in rows if int(r["block_size"]) == MAIN_BLOCK
                 and int(r["key_id"]) == MAIN_KEY_ID and r["recovery_variant"] == "A"]
    wm_psnr = aggregate_by(main_rows, (), "wm_psnr").get(())
    wm_ssim = aggregate_by(main_rows, (), "wm_ssim").get(())

    tamper_a_50 = [r for r in rows if r["condition"] == "tamper" and r["recovery_variant"] == "A"
                  and int(r["block_size"]) == MAIN_BLOCK and r["tamper_ratio_nominal"] == "0.50"]
    unmarked_50 = aggregate_by(tamper_a_50, (), "psnr_whole_unmarked").get(())
    marked_50 = aggregate_by(tamper_a_50, (), "psnr_whole_marked").get(())

    ours_psnr = f"{wm_psnr['mean']:.2f}" if wm_psnr else "--"
    ours_ssim = f"{wm_ssim['mean']:.4f}" if wm_ssim else "--"
    ours_recovered = f"{unmarked_50['mean']:.2f} @ 50\\% tamper" if unmarked_50 else "--"
    # This note used to be the hardcoded string literal "block/pixel precision/recall
    # $\geq$0.97", which is FALSE: measured pixel precision has mean 0.9489 with 78.4%
    # of main-grid rows BELOW 0.97. It was not conditioned on data, so the sanity gate
    # could never catch it -- the gate checks the CSV, never the generated LaTeX. It was
    # the only localization figure a reader of this table saw. Every number in this
    # cell is now computed from the rows in front of us.
    # ponytail: no gate on generated LaTeX -- the fix is to compute, not to add a
    # second checker. If more literals creep in here, gate the .tex files too.
    main_a = [r for r in rows if r["condition"] == "tamper" and r["recovery_variant"] == "A"
              and int(r["block_size"]) == MAIN_BLOCK]
    blk_p = aggregate_by(main_a, (), "block_precision").get(())
    blk_r = aggregate_by(main_a, (), "block_recall").get(())
    px_p = aggregate_by(main_a, (), "px_precision").get(())
    if blk_p and blk_r and px_p:
        ours_note = (f"block prec.\\ {blk_p['mean']:.4f}, recall {blk_r['mean']:.4f}, "
                     f"pixel prec.\\ {px_p['mean']:.4f} (Table~\\ref{{tab:localization}})")
    else:
        ours_note = "no main-grid tamper rows yet"
    if marked_50:
        ours_note += f"; marked (honest) output: {marked_50['mean']:.2f}~dB"

    lines = [
        r"\begin{tabular}{lcccl}",
        r"\toprule",
        r"Method & WM PSNR (dB) & WM SSIM & Recovered PSNR (dB) & Notes \\",
        r"\midrule",
    ]
    for method, psnr, ssim, rec, note in _PUBLISHED:
        lines.append(f"{method} & {psnr} & {ssim} & {rec} & {note} \\\\")
    lines.append(rf"\textbf{{Ours (measured, Variant A)}} & {ours_psnr} & {ours_ssim} & {ours_recovered} & {ours_note} \\")
    lines += [
        r"\midrule",
        r"\multicolumn{5}{p{0.9\linewidth}}{\footnotesize AuSR1, AuSR3 and Wu et al.\ "
        r"values are cited from their publications, not re-implementations. Our "
        r"``Recovered PSNR'' uses \texttt{psnr\_whole\_unmarked} -- the only quantity "
        r"comparable to those papers' whole-image, unrecoverable-region-left-as-received "
        r"convention; our default output instead marks unrecoverable regions explicitly "
        r"rather than fabricating content, which costs 10--15~dB of whole-image PSNR "
        r"relative to the unmarked figure shown here.} \\",
        r"\bottomrule",
        r"\end{tabular}",
    ]
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------------------
# Orchestration
# ---------------------------------------------------------------------------

TABLE_BUILDERS = [
    ("imperceptibility.tex", build_imperceptibility),
    ("localization_recovery.tex", build_localization_recovery),
    ("null_condition.tex", build_null_condition),
    ("ablation_blocksize.tex", build_ablation_blocksize),
    ("baseline_comparison.tex", build_baseline_comparison),
]


def main() -> None:
    parser = argparse.ArgumentParser(description="Generate paper LaTeX table bodies from output/runs.csv.")
    parser.add_argument("--csv", type=Path, default=sanity_gate.DEFAULT_CSV,
                        help="path to runs.csv (default: %(default)s)")
    args = parser.parse_args()

    passed, results = sanity_gate.run_checks(args.csv)
    if not passed:
        failed = [r for r in results if r["status"] == "FAIL"]
        print("#" * 78)
        print("# ABORTED -- sanity_gate reported hard/structural failures. Writing NOTHING.")
        print("# Fix the underlying data or bands before generating tables from it.")
        print("#" * 78)
        for r in failed:
            print(f"  FAIL: {r['name']} -- {r['detail']}")
        raise SystemExit(1)

    rows = load_runs_csv(args.csv)
    print(f"sanity_gate passed ({len(rows)} rows) -- generating tables into {TABLES_DIR}")
    for filename, builder in TABLE_BUILDERS:
        path = _write(filename, builder(rows))
        print(f"  wrote {path}")


if __name__ == "__main__":
    main()
