# Table 4: ablation_blocksize.tex
# ---------------------------------------------------------------------------

def build_ablation_blocksize(rows: list[dict]) -> str:
    """8x8 vs 4x4, USC-SIPI subset, Variant A: precision, recall, F1, IoU, rho, PSNR_omega."""
    usc_a = [r for r in rows if r["condition"] == "tamper" and r["recovery_variant"] == "A"
            and r["dataset"] == "usc_sipi"]
    b8 = [r for r in usc_a if int(r["block_size"]) == MAIN_BLOCK]
    b4 = [r for r in usc_a if int(r["block_size"]) == ABLATION_BLOCK]

    # PIXEL-level metrics are included deliberately: block-level precision/IoU are
    # saturated at 1.000 for BOTH block sizes, because block-level ground truth is
    # itself defined at whatever granularity is under test, so the comparison is
    # vacuous there. The trade-off the ablation exists to quantify only becomes
    # visible at pixel level, where a finer block genuinely tightens the mask.
    cols = [("block_precision", 3), ("px_precision", 4), ("px_iou", 4),
            ("recoverability_rate", 3), ("psnr_in_region", 2)]
    lines = [
        r"\begin{tabular}{lccccc}",
        r"\toprule",
        r"Block Size & Blk. Prec. & Px. Prec. & Px. IoU & $\rho$ & PSNR$_\Omega$ (dB) \\",
        r"\midrule",
    ]
    for label, sub in (("8$\\times$8 (main)", b8), ("4$\\times$4 (ablation)", b4)):
        aggs = {key: aggregate_by(sub, (), key).get(()) for key, _ in cols}
        cells = [_fmt_pm(aggs[k], d) for k, d in cols]
        lines.append(f"{label} & " + " & ".join(cells) + r" \\")
    lines += [
        r"\midrule",
        r"\multicolumn{6}{p{0.9\linewidth}}{\footnotesize Note: at block size 4 the "
        r"per-block payload is only 32 bits (\texttt{budget(4)}), so the authentication "
        r"tag drops from 32 to 16 bits, raising the per-block false-accept probability "
        r"from $2^{-32}$ to $2^{-16}$ -- on a $512\times512$ image with 16{,}384 blocks "
        r"that is an expected $\approx0.25$ false accepts per image. This is the honest "
        r"cost of finer localization, reported here as a finding, not omitted.} \\",
        r"\bottomrule",
        r"\end{tabular}",
    ]
    return "\n".join(lines) + "\n"


