"""Generates LaTeX `tabular` BODIES for the paper -- never a whole `table` float.

Each output file is a self-contained `\\begin{tabular}...\\end{tabular}` (booktabs
style, matching paper/IEEE_Paper.tex's existing \\usepackage{booktabs}), meant to be
\\input{} inside a hand-written `\\begin{table}...\\caption{}\\label{}...\\end{table}`.
This module never writes a caption or a label -- those are hand-tuned in the paper and
must never be clobbered by a regeneration here.

main() calls sanity_gate.run_checks() FIRST and refuses to write anything if a hard/
structural check fails. This is deliberately not a CI system, just one function call --
but it makes "generate tables from numbers nobody sanity-checked" structurally
impossible through this file's intended entry point.
"""

import argparse
import statistics
from pathlib import Path

import sanity_gate
from metrics import aggregate_by, load_runs_csv

ROOT = Path(__file__).resolve().parent.parent
TABLES_DIR = ROOT / "output" / "tables"

MAIN_BLOCK = 8
ABLATION_BLOCK = 4
MAIN_KEY_ID = 0
RATIOS = ("0.10", "0.25", "0.50")

# Readable labels matching the paper's own prose (see IEEE_Paper.tex, recall discussion).
TAMPER_LABELS = {
    "splice": "Copy-paste splicing",
    "inpaint_removal": "Object removal",
    "crop_refill": "Crop-and-refill",
    "noise": "Noise corruption",
}
TAMPER_ORDER = ("splice", "inpaint_removal", "crop_refill", "noise")


# ---------------------------------------------------------------------------
# LaTeX helpers
# ---------------------------------------------------------------------------

_LATEX_SPECIALS = {
    "\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#",
    "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}",
}


def esc(text: str) -> str:
    """Escape LaTeX special characters in a text cell (backslash first, or double-escapes)."""
    out = str(text)
    out = out.replace("\\", _LATEX_SPECIALS["\\"])
    for ch, rep in _LATEX_SPECIALS.items():
        if ch == "\\":
            continue
        out = out.replace(ch, rep)
    return out


HEADER_COMMENT = "% generated by make_tables.py -- do not edit by hand\n"


def _fmt(val: float, decimals: int) -> str:
    if val != val:  # NaN
        return "--"
    if val in (float("inf"), float("-inf")):
        return r"$\infty$"
    return f"{val:.{decimals}f}"


def _fmt_pm(agg: dict | None, decimals: int) -> str:
    """'mean $\\pm$ std', or '--' if there is no data for this group."""
    if agg is None or agg["n"] == 0:
        return "--"
    return f"{_fmt(agg['mean'], decimals)} $\\pm$ {_fmt(agg['std'], decimals)}"


def _write(name: str, body: str) -> Path:
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    path = TABLES_DIR / name
    path.write_text(HEADER_COMMENT + body, encoding="utf-8")
    return path


# ---------------------------------------------------------------------------
# Table 1: imperceptibility.tex
# ---------------------------------------------------------------------------

def build_imperceptibility(rows: list[dict]) -> str:
    """Per-image PSNR/SSIM (8 USC-SIPI shown) + a mean row over all 32 corpus images."""
    # Canonical embed per image: block=8 (the main config), key=0 (the main-grid key).
    # wm_psnr/wm_ssim are identical across every row sharing (image, variant, block,
    # key) -- embed_image() is cached by exactly that tuple -- so any matching row works.
    src = [r for r in rows if int(r["block_size"]) == MAIN_BLOCK and int(r["key_id"]) == MAIN_KEY_ID]
    psnr = aggregate_by(src, ("image_name", "recovery_variant"), "wm_psnr")
    ssim = aggregate_by(src, ("image_name", "recovery_variant"), "wm_ssim")

    usc_names = sorted({r["image_name"] for r in src if r["dataset"] == "usc_sipi"})
    all_names = sorted({r["image_name"] for r in src})

    lines = [
        r"\begin{tabular}{lcccc}",
        r"\toprule",
        r"Image & PSNR-A (dB) & SSIM-A & PSNR-B (dB) & SSIM-B \\",
        r"\midrule",
    ]
    for name in usc_names:
        pa = psnr.get((name, "A")); sa = ssim.get((name, "A"))
        pb = psnr.get((name, "B")); sb = ssim.get((name, "B"))
        # Plain values, no "$\pm$ 0.00": embedding is deterministic given
        # (image, variant, block, key), so a per-image std over identical rows is
        # exactly zero and printing it is noise that invites a reviewer question.
        lines.append(f"{esc(name.capitalize())} & {_fmt(pa['mean'], 2) if pa else '--'} & "
                     f"{_fmt(sa['mean'], 4) if sa else '--'} & "
                     f"{_fmt(pb['mean'], 2) if pb else '--'} & "
                     f"{_fmt(sb['mean'], 4) if sb else '--'} \\\\")
    # mean row: unweighted mean OVER THE 32 PER-IMAGE MEANS, not over underlying rows --
    # every image should count once regardless of how many CSV rows reference it.
    def _corpus_mean(agg_table: dict, variant: str) -> float:
        vals = [agg_table[(n, variant)]["mean"] for n in all_names if (n, variant) in agg_table]
        return statistics.mean(vals) if vals else float("nan")

    mean_pa, mean_sa = _corpus_mean(psnr, "A"), _corpus_mean(ssim, "A")
    mean_pb, mean_sb = _corpus_mean(psnr, "B"), _corpus_mean(ssim, "B")
    lines += [
        r"\midrule",
        rf"\textbf{{Mean ({len(all_names)} images)}} & \textbf{{{_fmt(mean_pa, 2)}}} & "
        rf"\textbf{{{_fmt(mean_sa, 4)}}} & \textbf{{{_fmt(mean_pb, 2)}}} & "
        rf"\textbf{{{_fmt(mean_sb, 4)}}} \\",
        r"\bottomrule",
        r"\end{tabular}",
    ]
    # Corpus note, per spec: 32 images total (8 USC-SIPI shown individually above + 24
    # Kodak folded only into the mean row), not the 40 some published corpora report.
    note = "% corpus is 32 images (8 USC-SIPI + 24 Kodak), not 40 -- the mean row above averages all 32\n"
    return note + "\n".join(lines) + "\n"


