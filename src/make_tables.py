# Table 3: null_condition.tex
# ---------------------------------------------------------------------------

def build_null_condition(rows: list[dict]) -> str:
    """Null-condition false-positive rates + rule-of-three 95% upper bound on 3/n."""
    null_rows = [r for r in rows if r["condition"] == "null"]
    n_images = len({r["image_name"] for r in null_rows})
    n_variants = len({r["recovery_variant"] for r in null_rows})
    n_keys = len({int(r["key_id"]) for r in null_rows})

    n_block_checks = sum(int(r["n_blocks_total"]) for r in null_rows)
    n_fp_blocks = sum(int(r["n_false_positive_blocks"]) for r in null_rows)
    block_fpr = (n_fp_blocks / n_block_checks) if n_block_checks else float("nan")
    px_fpr_agg = aggregate_by(null_rows, (), "px_fpr").get(())
    px_fpr = px_fpr_agg["mean"] if px_fpr_agg else float("nan")
    # Rule-of-three: with 0 observed events in n independent trials, the 95% upper
    # confidence bound on the true per-trial rate is 3/n. Pure arithmetic, no scipy.
    rule_of_three = (3.0 / n_block_checks) if n_block_checks else float("nan")

    lines = [
        r"\begin{tabular}{lc}",
        r"\toprule",
        r"Quantity & Value \\",
        r"\midrule",
        rf"Null-condition rows & {len(null_rows)} \\",
        rf"Images $\times$ Variants $\times$ Keys & {n_images} $\times$ {n_variants} $\times$ {n_keys} \\",
        rf"Independent block verifications ($n$) & {n_block_checks} \\",
        rf"False-positive blocks (sum) & {n_fp_blocks} \\",
        rf"Block-level false-positive rate & {_fmt(block_fpr, 6)} \\",
        rf"Pixel-level false-positive rate (mean px\_fpr) & {_fmt(px_fpr, 6)} \\",
        r"\midrule",
        rf"Rule-of-three 95\% upper bound, $3/n$ & {_fmt(rule_of_three, 8)} \\",
        r"\bottomrule",
        r"\end{tabular}",
    ]
    return "\n".join(lines) + "\n"


