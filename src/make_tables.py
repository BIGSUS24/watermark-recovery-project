# Table 2: localization_recovery.tex
# ---------------------------------------------------------------------------

def build_localization_recovery(rows: list[dict]) -> str:
    """4 tamper classes x 3 ratios, Variant A, main grid (block=8) only."""
    main_a = [r for r in rows if r["condition"] == "tamper" and r["recovery_variant"] == "A"
             and int(r["block_size"]) == MAIN_BLOCK]

    cols = [("block_precision", 3), ("block_recall", 3), ("block_f1", 3), ("block_iou", 3),
            ("recoverability_rate", 3), ("psnr_in_region", 2), ("psnr_whole_unmarked", 2)]
    aggs = {key: aggregate_by(main_a, ("tamper_class", "tamper_ratio_nominal"), key) for key, _ in cols}

    lines = [
        r"\begin{tabular}{llccccccc}",
        r"\toprule",
        r"Tamper Class & Ratio & Prec. & Recall & F1 & IoU & $\rho$ & "
        r"PSNR$_\Omega$ (dB) & PSNR$_{\mathrm{unmarked}}$ (dB) \\",
        r"\midrule",
    ]
    for cls in TAMPER_ORDER:
        for i, ratio_s in enumerate(RATIOS):
            key = (cls, ratio_s)
            label = esc(TAMPER_LABELS[cls]) if i == 0 else ""
            cells = [_fmt_pm(aggs[k].get(key), d) for k, d in cols]
            lines.append(f"{label} & {ratio_s} & " + " & ".join(cells) + r" \\")
        if cls != TAMPER_ORDER[-1]:
            lines.append(r"\addlinespace")
    lines += [r"\bottomrule", r"\end{tabular}"]

    # Footnote data: mean +/- std ACHIEVED ratio per NOMINAL bucket. tamper_ratio_achieved
    # is deliberately kept as a string by metrics.load_runs_csv (see its NUMERIC_FIELDS
    # comment), so it is converted here, not aggregated via aggregate_by.
    achieved_notes = []
    for ratio_s in RATIOS:
        vals = [float(r["tamper_ratio_achieved"]) for r in main_a if r["tamper_ratio_nominal"] == ratio_s]
        if vals:
            mean = statistics.mean(vals)
            std = statistics.pstdev(vals) if len(vals) >= 2 else 0.0
            achieved_notes.append(f"{ratio_s} (achieved {mean:.3f} $\\pm$ {std:.3f})")
        else:
            achieved_notes.append(f"{ratio_s} (achieved: no data yet)")
    footnote = ("% Achieved tamper ratio per nominal bucket -- grouping by the nominal value is\n"
               "% never exact area matching: " + "; ".join(achieved_notes) + "\n")
    return footnote + "\n".join(lines) + "\n"


